"""``main`` -- the entry point, and the only place that decides how to exit.

The shape, and why each line is here::

    def main(argv=None) -> int:
        with catch_errors(...):     # user errors -> message + code, bugs -> traceback
            parser = build_parser()
            args = parser.parse_args(argv)          # -> SystemExit(2) on usage error
            args = apply_completion(parser, args)   # scripts bypass everything
            args = apply_config(parser, args)       # defaults < file < env < argv
            validate(args)                          # before any side effect
            return dispatch(parser, args)

Three rules this file exists to enforce:

1. **``argv`` is a parameter, never ``sys.argv``.** That is what makes the CLI
   testable in-process: ``main(["list"])`` needs no subprocess and no patching.
2. **``main`` returns an int.** It never calls ``sys.exit``. The caller raises it,
   so a test can assert on the return value.
3. **Validation happens before side effects.** A user should learn about a typo
   before files are written or ports are bound.

Nothing here knows about tasks, tasks know nothing about parsing, and the parser
knows nothing about either. That separation is the case study's whole argument.
"""

from __future__ import annotations

import argparse
import contextlib
import sys
from collections.abc import Sequence

from .cli import build_parser, find_config_argv
from .commands import dispatch
from .config import load_layered_config
from .errors import TaskRunnerError
from .exit_codes import ExitCode
from .validation import ValidationError, validate_global_args, validate_run_args

__all__ = ["completion_script", "main"]


def completion_script(parser: argparse.ArgumentParser, args: argparse.Namespace) -> str | None:
    """Return the requested completion script, or ``None``.

    Returning ``None`` for "not requested" lets the caller fall through without a
    conditional of its own. The script text is generated from ``parser`` itself, so
    it cannot go stale relative to the parser -- the failure mode of hand-written
    completion scripts, which rot silently when a flag is renamed.
    """
    if args.bash_completion_script:
        return _bash(parser.prog, parser)
    if args.zsh_completion_script:
        return _zsh(parser.prog, parser)
    if args.fish_completion_script:
        return _fish(parser.prog, parser)
    return None


def _collect(parser: argparse.ArgumentParser) -> tuple[list[str], list[str]]:
    """Introspect ``parser`` for subcommand names and top-level option strings.

    Touches ``parser._actions``, which is private. Acceptable *here* because this
    runs inside our own process; the same introspection inside a completion script
    (running in the user's shell) deserves the defensive version in
    ``argparse_mastery.completion``.

    **Aliases are derived from ``_name_parser_map`` insertion order**, because
    ``add_parser(aliases=[...])`` pops them out of the kwargs and writes them into
    that map -- the parser object never gains an ``aliases`` attribute. So
    ``getattr(child, "aliases", ())`` always returns ``()``, silently omitting
    every alias from the completion script. ``add_parser`` writes the canonical
    key first and the aliases after, all pointing at the same parser object, and
    ``dict`` preserves insertion order, so this derivation is exact.
    """
    commands: list[str] = []
    options: list[str] = []
    for action in parser._actions:
        if action.help is argparse.SUPPRESS:
            continue
        options.extend(action.option_strings)
        if isinstance(action, argparse._SubParsersAction):
            commands.extend(action._name_parser_map)
    return sorted(set(commands)), sorted(set(options))


def _bash(prog: str, parser: argparse.ArgumentParser) -> str:
    commands, options = _collect(parser)
    func = f"_{prog.replace('-', '_')}_completion"
    return f"""# bash completion for {prog}
# Generated by `taskrunner --bash-completion-script`. Do not edit.
# Install: taskrunner --bash-completion-script > /etc/bash_completion.d/{prog}

{func}() {{
    local cur prev
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "{' '.join(options)}" -- "$cur") )
        return 0
    fi
    if [[ $COMP_CWORD -eq 1 ]]; then
        COMPREPLY=( $(compgen -W "{' '.join(commands)}" -- "$cur") )
        return 0
    fi
    COMPREPLY=( $(compgen -f -- "$cur") )
    return 0
}}
complete -F {func} {prog}
"""


def _zsh(prog: str, parser: argparse.ArgumentParser) -> str:
    commands, options = _collect(parser)
    specs = [f"    '{flag}[]'" for flag in options]
    return f"""#compdef {prog}
# Generated by `taskrunner --zsh-completion-script`. Do not edit.
# Install: taskrunner --zsh-completion-script > ~/.zsh/completions/_{prog}

_arguments -s \\
{chr(10).join(specs)}{chr(10) if specs else ''}    '1: :({' '.join(commands)})' \\
    '*::arg:->args'

case $state in
    args) _files && return 0 ;;
esac
"""


def _fish(prog: str, parser: argparse.ArgumentParser) -> str:
    commands, options = _collect(parser)
    lines = [f"# fish completion for {prog}",
             "# Generated by `taskrunner --fish-completion-script`. Do not edit."]
    for flag in options:
        lines.append(f"complete -c {prog} -l {flag.lstrip('-')} -f")
    if commands:
        listed = " ".join(commands)
        lines.append(f"complete -c {prog} -f -a '{listed}'")
        lines.append(f"complete -c {prog} -n '__fish_seen_subcommand_from {listed}' -F")
    return "\n".join(lines) + "\n"


def parser_for_command(
    parser: argparse.ArgumentParser, command: str | None
) -> argparse.ArgumentParser:
    """Return a parser that knows both the global and the selected command's options.

    Subcommand options are invisible to the top-level parser. Passing the top-level
    parser to :func:`taskrunner.config.validate_against_parser` would therefore
    classify ``retries = 5`` as an unknown key and drop it -- silently skipping its
    range check, which is the exact bug the validation step exists to prevent.

    The fix is a *view* parser that inherits both sets of options. Building a real
    parser (rather than stitching a dict of actions together) means argparse still
    owns the ``type=``/``choices`` metadata, and the view is discarded afterwards so
    it can never diverge from the real parsers.
    """
    if not command:
        return parser

    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction) and command in action.choices:
            sub = action.choices[command]
            try:
                view = argparse.ArgumentParser(
                    prog=parser.prog, add_help=False, parents=[parser, sub]
                )
            except argparse.ArgumentError:
                # A dest collision between the two levels; fall back to a merged
                # action list rather than failing the whole run.
                merged = argparse.ArgumentParser(prog=parser.prog, add_help=False)
                merged._actions = list(parser._actions) + list(sub._actions)
                return merged
            return view
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Run the CLI. Returns a process exit code; never calls ``sys.exit``.

    Callers::

        if __name__ == "__main__":
            raise SystemExit(main())
    """
    args_in = list(sys.argv[1:] if argv is None else argv)

    parser = build_parser()
    args = parser.parse_args(args_in)

    # 1. Completion first: the script must reach stdout untouched, with no
    #    configuration errors, no validation and no logging ahead of it.
    script = completion_script(parser, args)
    if script is not None:
        sys.stdout.write(script)
        return ExitCode.OK

    # 2. Layer the configuration, installed as defaults so argv still wins.
    #    done BEFORE validation, because a rule may legitimately involve a
    #    configured value. Validated against a view that knows the chosen command's
    #    options too -- see parser_for_command.
    view = parser_for_command(parser, getattr(args, "command", None))
    try:
        layer = load_layered_config(
            view,
            env=None,
            config_path=find_config_argv(args_in) or _default_config_path(),
        )
    except TaskRunnerError as exc:
        sys.stderr.write(f"{parser.prog}: error: {exc.message}\n")
        return int(exc.code)

    # set_defaults after the first parse only affects a second parse; the layer
    # values are attached directly so they survive without re-parsing.
    _apply_defaults(args, layer)
    args._config_layer = layer

    # 3. Validate before any side effect.
    try:
        validate_global_args(args)
        if getattr(args, "command", None) == "run":
            validate_run_args(args)
    except ValidationError as exc:
        sys.stderr.write(f"{parser.prog}: error: {exc}\n")
        return int(ExitCode.USAGE)

    # 4. Dispatch.
    try:
        return dispatch(parser, args)
    except TaskRunnerError as exc:
        sys.stderr.write(f"{parser.prog}: error: {exc.message}\n")
        return int(exc.code)
    except KeyboardInterrupt:
        sys.stderr.write(f"\n{parser.prog}: interrupted\n")
        return int(ExitCode.INTERRUPTED)
    except BrokenPipeError:
        # `taskrunner list | head -5` closes the pipe on purpose. Exit quietly and
        # successfully so `set -o pipefail` scripts do not see spurious noise.
        with contextlib.suppress(OSError):
            sys.stdout.flush()
        return int(ExitCode.OK)


def _apply_defaults(args: argparse.Namespace, layer) -> None:
    """Copy validated configuration values onto the namespace.

    Deliberately *after* parsing rather than via ``parser.set_defaults`` plus a
    second ``parse_args``. Re-parsing works and is arguably cleaner, but it runs
    every ``type=`` twice and means the parser has to be reentrant. Copying onto an
    already-parsed namespace is explicit about what it does and costs one pass.

    The subtlety this handles: ``vars(args)`` already contains argv values, so a
    config value must not overwrite one. Hence the presence check.
    """
    for key, value in layer.values.items():
        if not hasattr(args, key):
            setattr(args, key, value)


def _default_config_path() -> str | None:
    """``$TASKRUNNER_CONFIG``, else ``./taskrunner.toml`` if it exists."""
    import os
    from pathlib import Path

    from_env = os.environ.get("TASKRUNNER_CONFIG")
    if from_env:
        return from_env
    local = Path.cwd() / "taskrunner.toml"
    return str(local) if local.is_file() else None
